#!/usr/bin/env bash
# Generate root-only Nginx Geo/Map variables from Cloudflare's OFFICIAL edge IPs.
# This does not install the optional site config or reload Nginx.
# Never run when the origin is behind an unverified intermediary or when
# Cloudflare visitor-location Managed Transform is not enabled.
set -Eeuo pipefail
umask 077
[[ "$(id -u)" -eq 0 ]] || { echo 'STOP: run with sudo.' >&2; exit 1; }
ENV=/etc/iradios/staging/backend.env
OUT=/etc/nginx/conf.d/iradios-stage-cloudflare-geo.conf
[[ -f "$ENV" && ! -L "$ENV" && "$(stat -c '%a' "$ENV")" == 600 ]] || {
  echo 'STOP: secure staging backend.env is required.' >&2; exit 1;
}
[[ ! -L "$OUT" ]] || { echo 'STOP: output may not be a symlink.' >&2; exit 1; }
command -v curl >/dev/null
command -v python3 >/dev/null
install -d -o root -g root -m 755 /etc/nginx/conf.d
tmp=$(mktemp -d)
trap 'rm -rf -- "$tmp"' EXIT
# Retain the original root-only map until the candidate passes Nginx syntax.
if [[ -f "$OUT" ]]; then cp --preserve=mode,ownership -- "$OUT" "$tmp/previous"; fi
curl --fail --silent --show-error --location --max-time 20 \
  https://www.cloudflare.com/ips-v4 -o "$tmp/ips-v4"
curl --fail --silent --show-error --location --max-time 20 \
  https://www.cloudflare.com/ips-v6 -o "$tmp/ips-v6"
python3 - "$tmp/ips-v4" "$tmp/ips-v6" "$ENV" "$OUT" <<'PY'
import ipaddress, os, pathlib, re, sys, tempfile
v4_file,v6_file,env_file,output=sys.argv[1:]
entries=pathlib.Path(env_file).read_text().splitlines()
values=[line.split('=',1)[1] for line in entries
        if line.startswith('IRADIOS_TRUSTED_GEO_SECRET=')]
if len(values)!=1 or not re.fullmatch(r'[a-fA-F0-9]{64}',values[0]):
    raise SystemExit('STOP: generate IRADIOS_TRUSTED_GEO_SECRET with openssl rand -hex 32.')
secret=values[0]
networks=[]
for path,version,minimum in ((v4_file,4,8),(v6_file,6,4)):
    source=pathlib.Path(path).read_text().splitlines()
    if len(source)<minimum:
        raise SystemExit('STOP: incomplete official Cloudflare edge IP list.')
    for entry in source:
        network=ipaddress.ip_network(entry.strip(),strict=True)
        if network.version!=version or not network.is_global or network.prefixlen==0:
            raise SystemExit('STOP: untrusted Cloudflare edge IP range.')
        networks.append(network)
if len({str(net) for net in networks})!=len(networks):
    raise SystemExit('STOP: duplicate edge CIDR entries.')
# Nginx checks the actual TCP peer. If other proxy real_ip rewriting occurs,
# remote_addr may be the visitor and will fail closed until verified separately.
lines=[
'# Generated by ops/generate-stage-cloudflare-geo.sh, root-only, do not commit.',
'geo $iradios_stage_cloudflare_edge {',
'    default 0;',
]
lines.extend(f'    {network} 1;' for network in networks)
lines.extend([
'}',
'map $iradios_stage_cloudflare_edge $iradios_stage_geo_auth {',
'    default "";',
f'    1 "{secret}";',
'}',
'map $iradios_stage_cloudflare_edge $iradios_stage_geo_country {',
'    default "";',
'    1 $http_cf_ipcountry;',
'}',
'map $iradios_stage_cloudflare_edge $iradios_stage_geo_region {',
'    default "";',
'    1 $http_cf_region;',
'}',
'map $iradios_stage_cloudflare_edge $iradios_stage_geo_city {',
'    default "";',
'    1 $http_cf_ipcity;',
'}',
''])
directory=os.path.dirname(output)
fd,tmp=tempfile.mkstemp(prefix='.iradios-stage-geo-',dir=directory)
try:
    with os.fdopen(fd,'w') as handle:
        handle.write('\n'.join(lines))
    os.chmod(tmp,0o600)
    os.replace(tmp,output)
except BaseException:
    if os.path.exists(tmp): os.remove(tmp)
    raise
PY
if ! nginx -t; then
  if [[ -f "$tmp/previous" ]]; then
    cp --preserve=mode,ownership -- "$tmp/previous" "$OUT"
  else
    rm -f -- "$OUT"
  fi
  echo 'STOP: Nginx rejected geo maps; prior configuration restored.' >&2
  exit 1
fi
echo 'Cloudflare edge Geo/Map configuration generated and Nginx syntax tested.'
echo 'NOT activated: review Cloudflare Managed Transform, origin path and site geo template before enabling.'
